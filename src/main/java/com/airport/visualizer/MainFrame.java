    /** Look and feel tuned to the app palette; falls back silently to the default one. */
    private static void installLookAndFeel() {
        try {
            for (UIManager.LookAndFeelInfo info : UIManager.getInstalledLookAndFeels()) {
                if ("Nimbus".equals(info.getName())) {
                    UIManager.put("control", Theme.BG);
                    UIManager.put("nimbusBase", Theme.SIDEBAR);
                    UIManager.put("nimbusBlueGrey", Theme.BORDER_STRONG);
                    UIManager.put("nimbusFocus", Theme.PRIMARY);
                    UIManager.put("nimbusSelectionBackground", Theme.PRIMARY);
                    UIManager.put("nimbusSelection", Theme.PRIMARY);
                    UIManager.put("nimbusLightBackground", Theme.SURFACE);
                    UIManager.put("text", Theme.TEXT);
                    UIManager.put("info", Theme.SURFACE);
                    UIManager.setLookAndFeel(info.getClassName());
                    UIManager.getLookAndFeelDefaults().put("defaultFont", new FontUIResource(Theme.regular(13.5f)));
                    break;
                }
            }
        } catch (ReflectiveOperationException | javax.swing.UnsupportedLookAndFeelException ex) {
            java.util.logging.Logger.getLogger(MainFrame.class.getName())
                    .log(java.util.logging.Level.WARNING, "Nimbus look and feel unavailable", ex);
        }
        UIManager.put("ToolTip.font", new FontUIResource(Theme.regular(13f)));
    }

    /** Any unexpected error is shown politely instead of silently killing the app. */
    private static void installCrashGuard() {
        Thread.setDefaultUncaughtExceptionHandler((thread, ex) -> {
            java.util.logging.Logger.getLogger(MainFrame.class.getName())
                    .log(java.util.logging.Level.SEVERE, "Unexpected error", ex);
            SwingUtilities.invokeLater(() -> JOptionPane.showMessageDialog(null,
                    "Something unexpected happened, but your work is safe.\n" + ex.getClass().getSimpleName()
                    + (ex.getMessage() == null ? "" : ": " + ex.getMessage()),
                    "Oops!", JOptionPane.WARNING_MESSAGE));
        });
    }

